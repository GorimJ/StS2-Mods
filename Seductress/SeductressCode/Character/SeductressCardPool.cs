using System;
using System.Collections.Generic;
using System.Linq;
using BaseLib.Abstracts;
using MegaCrit.Sts2.Core.Models;
using MegaCrit.Sts2.Core.Unlocks;
using Seductress.SeductressCode.Extensions;
using Godot;

namespace Seductress.SeductressCode.Character;

public class SeductressCardPool : CustomCardPoolModel
{
    /// <summary>
    /// Cards that live in this pool for colour and identity but must never be <b>offered</b>.
    ///
    /// [Claude-Code] There is no per-card "not draftable" flag: pool membership comes from the
    /// [Pool] attribute at registration time, and BaseLib throws if a model has none. The pool's
    /// own epoch filter is the one hook that runs on every draft, so exclusion goes here.
    ///
    /// <b>Milk</b> is generated by lactation into the combat pile and never enters the master deck.
    ///
    /// [Gorim] <b>Milking Grip leaves the draft pool</b> now that it is the 100 ml Ass threshold
    /// reward. If it stayed draftable an early pick would skip the progression entirely and the
    /// thresholds would become decoration.
    /// </summary>
    private static readonly HashSet<Type> NotDraftable =
    [
        typeof(Cards.Milk),
        typeof(Cards.MilkingGrip)
    ];

    protected override IEnumerable<CardModel> FilterThroughEpochs(UnlockState unlockState, IEnumerable<CardModel> cards) =>
        base.FilterThroughEpochs(unlockState, cards)
            .Where(c => !NotDraftable.Contains(c.GetType()))
            .ToList();

    public override string Title => Seductress.CharacterId; //This is not a display name.
    
    public override string BigEnergyIconPath => "charui/big_energy.png".ImagePath();
    public override string TextEnergyIconPath => "charui/text_energy.png".ImagePath();


    /* These HSV values will determine the color of your card back.
    They are applied as a shader onto an already colored image,
    so it may take some experimentation to find a color you like.
    Generally they should be values between 0 and 1. */
    public override float H => 1f; //Hue; changes the color.
    public override float S => 1f; //Saturation
    public override float V => 1f; //Brightness
    
    //Alternatively, leave these values at 1 and provide a custom frame image.
    /*public override Texture2D CustomFrame(CustomCardModel card)
    {
        //This will attempt to load Seductress/images/cards/frame.png
        return PreloadManager.Cache.GetTexture2D("cards/frame.png".ImagePath());
    }*/

    //Color of small card icons
    public override Color DeckEntryCardColor => new("ffffff");
    
    public override bool IsColorless => false;
}