/// <summary>
/// The three hole insets (mouth, womb, ass): cutaway pictures that show how full each hole is and
/// which one is in use.
///
/// [Gorim, 2026-11-21] "Mod needs to display proportional filling, holes in use on whatever the
/// last attack is, cum entering on each attack and a larger spurt and leaving the hole when the
/// enemy is finished." Then, answering how it is driven: a row along the top of the screen;
/// thickness by enemy type; attacks are the player's Attack cards and "finished" is the enemy
/// dying, "but the cock stays thrusting until the next card/death".
///
/// [Claude] Details he did not rule on:
/// - "By enemy type" is read from the encounter: normal fights 1.0, elites 1.35, bosses 1.8.
/// - A non-Attack card stops the thrusting but leaves the cock resting inside; only an Attack
///   into another hole (or to Skin) or a finish takes it out.
/// - A multi-hit card does not restart the entry animation on every hit; the fill catches up
///   with the real amount at the spurt.
/// - The Womb picture is full at one stage (500 ml) and the Ass at its cap; both stop at full.
///
/// The scenes are the animation session's (<c>scenes/insets</c>, generated by
/// <c>tools/seductress_rig/insets/build_insets.py</c>). Their animations move the shader's
/// <c>depth</c> and <c>spurt</c>; this class sets <c>fill</c> and <c>girth</c> and, between
/// animations, drives <c>depth</c> itself for the idle thrust.
/// </summary>
public partial class HoleInsets : Node2D
{
    private const float Scale = 0.2f;          // of a 1024 px picture
    private const float Gap = 12f;
    private const float Top = 96f;
    private const float ThrustPeriod = 0.6f;

    /// <summary>The row for the combat on screen, if there is one. Game hooks talk to this.</summary>
    public static HoleInsets? Current { get; private set; }

    private enum Mode { Out, Resting, Thrusting }

    private sealed class Inset
    {
        public required ShaderMaterial Material;
        public required AnimationPlayer Anim;
        public Mode Mode = Mode.Out;
        public float Shown;          // fill currently drawn
        public float Hold;           // seconds until the drawn fill may move (the spurt)
        public float Phase;          // idle thrust clock
        public float Depth = -1f;
    }

    private static readonly Hole[] Order = [Hole.Mouth, Hole.Pussy, Hole.Ass];
    private readonly Dictionary<Hole, Inset> _insets = new();
    private readonly Dictionary<Hole, Label> _readouts = new();
    private Label? _status;
    private Player? _player;

    private static readonly Color Ink = new(1f, 0.92f, 0.96f);
    private static readonly Color Active = new(1f, 0.82f, 0.48f);

    private Label Readout(Vector2 position, float width, HorizontalAlignment align)
    {
        var label = new Label { Position = position, Size = new Vector2(width, 22f), HorizontalAlignment = align };
        label.AddThemeFontSizeOverride("font_size", 16);
        label.AddThemeColorOverride("font_color", Ink);
        label.AddThemeColorOverride("font_shadow_color", new Color(0, 0, 0, 0.9f));
        label.AddThemeConstantOverride("shadow_offset_x", 1);
        label.AddThemeConstantOverride("shadow_offset_y", 2);
        AddChild(label);
        return label;
    }

    /// <summary>
    /// [Gorim, 2026-11-21] These replace the debug text box. Under each picture: what is in the
    /// hole against its cap; the hole a Continuing card would use is in gold. Right of the row:
    /// Climaxes this combat. [Claude] The wording and placement are mine.
    /// </summary>
    private void RefreshReadouts()
    {
        if (_player is null) return;
        var r = Reservoirs.Of(_player.RunState);
        var continuing = ClimaxModel.Instance.ContinuingHole;

        foreach (var (hole, label) in _readouts)
        {
            label.Text = hole switch
            {
                Hole.Mouth => $"Mouth {r.Mouth}" + (r.Precum > 0 ? $" + {r.Precum} pre" : "") + $" / {ReservoirState.MouthCap}",
                Hole.Pussy => $"Womb {r.Womb}" + (r.WombPrecum > 0 ? $" ({r.WombPrecum} pre)" : "") +
                              (r.PregnancyStage > 0 ? $", stage {r.PregnancyStage}"
                                  : $" / {ReservoirState.WombStage}"),
                _ => $"Ass {r.Ass}" + (r.AssPrecum > 0 ? $" ({r.AssPrecum} pre)" : "") + $" / {ReservoirState.AssCap}" +
                     (r.PlugIn ? ", plugged" : "")
            };
            label.AddThemeColorOverride("font_color", hole == continuing ? Active : Ink);
        }

        if (_status is not null)
        {
            var climaxes = ClimaxModel.Instance.ClimaxesThisCombat;
            _status.Text = climaxes > 0 ? $"Climaxes this combat: {climaxes}" : "";
        }
    }

    public void Initialize(Player player) => _player = player;

    public override void _Ready()
    {
        var size = 1024f * Scale;
        var width = Order.Length * size + (Order.Length - 1) * Gap;
        var left = (GetViewportRect().Size.X - width) / 2f;

        for (var i = 0; i < Order.Length; i++)
        {
            var name = Order[i] switch { Hole.Mouth => "mouth", Hole.Pussy => "womb", _ => "ass" };
            var scene = GD.Load<PackedScene>($"{MainFile.ResPath}/scenes/insets/inset_{name}.tscn");
            if (scene is null)
            {
                MainFile.Logger.Info($"[Seductress] inset_{name}.tscn is missing from the pck; insets not shown");
                continue;
            }

            var node = scene.Instantiate<Node2D>();
            node.Scale = new Vector2(Scale, Scale);
            node.Position = new Vector2(left + i * (size + Gap), Top);
            AddChild(node);

            if (node.GetNodeOrNull<Sprite2D>("Pic")?.Material is not ShaderMaterial material ||
                node.GetNodeOrNull<AnimationPlayer>("Anim") is not { } anim)
            {
                MainFile.Logger.Info($"[Seductress] inset_{name}.tscn has no Pic material or Anim; skipped");
                continue;
            }

            var inset = new Inset { Material = material, Anim = anim };
            inset.Shown = TargetFill(Order[i]);
            material.SetShaderParameter("fill", Level(Order[i], inset.Shown));
            _insets[Order[i]] = inset;
            _readouts[Order[i]] = Readout(new Vector2(node.Position.X, Top + size + 2f), size, HorizontalAlignment.Center);
        }

        _status = Readout(new Vector2(left + width + 16f, Top), 260f, HorizontalAlignment.Left);
        RefreshReadouts();

        Current = this;
    }

    public override void _ExitTree()
    {
        if (Current == this) Current = null;
    }

    private float TargetFill(Hole hole)
    {
        if (_player is null) return 0f;
        var r = Reservoirs.Of(_player.RunState);
        var fill = hole switch
        {
            Hole.Mouth => (r.Mouth + r.Precum) / (float)ReservoirState.MouthCap,
            Hole.Pussy => r.Womb / (float)ReservoirState.WombStage,
            Hole.Ass => r.Ass / (float)ReservoirState.AssCap,
            _ => 0f
        };
        return Mathf.Clamp(fill, 0f, 1f);
    }

    public override void _Process(double delta)
    {
        var dt = (float)delta;
        RefreshReadouts();
        foreach (var (hole, inset) in _insets)
        {
            // Fill: held until the spurt, then eased to the real amount.
            if (inset.Hold > 0f) inset.Hold -= dt;
            else
            {
                var target = TargetFill(hole);
                if (!Mathf.IsEqualApprox(inset.Shown, target))
                {
                    inset.Shown = Mathf.MoveToward(inset.Shown, target, Math.Max(Math.Abs(target - inset.Shown) * 4f, 0.05f) * dt);
                    inset.Material.SetShaderParameter("fill", Level(hole, inset.Shown));
                }
            }

            // Depth: the animations own it while they play; between them, thrust or settle.
            if (inset.Anim.IsPlaying()) continue;
            if (inset.Mode == Mode.Thrusting)
            {
                inset.Phase += dt;
                inset.Depth = 0.55f - 0.45f * Mathf.Cos(Mathf.Tau * inset.Phase / ThrustPeriod);
                inset.Material.SetShaderParameter("depth", inset.Depth);
            }
            else if (inset.Mode == Mode.Resting && !Mathf.IsEqualApprox(inset.Depth, 0.1f))
            {
                inset.Depth = Mathf.MoveToward(inset.Depth, 0.1f, 3f * dt);
                inset.Material.SetShaderParameter("depth", inset.Depth);
            }
        }
    }

    /// <summary>
    /// [Gorim, 2026-11-21] "I think the holes increase by linear length, rather than volume/area
    /// fill (most notable in the womb)." The shader's <c>fill</c> is the height of the surface, so
    /// half full drew as half the height, which in a shape that widens upward is far less than
    /// half the area.
    ///
    /// [Claude] These tables turn a share of the hole's area into the surface height that shows
    /// it: entry k is the height at k/10 of the area, measured from each <c>*_mask.png</c> between
    /// the scene's <c>fill_at</c> rows. Done here and not in the shader because the shader is
    /// generated by the animation session's build script. Re-measure if the masks change.
    /// </summary>
    private static readonly Dictionary<Hole, float[]> AreaToLevel = new()
    {
        [Hole.Mouth] = [0f, 0.234f, 0.344f, 0.441f, 0.526f, 0.606f, 0.683f, 0.760f, 0.841f, 0.922f, 1f],
        [Hole.Pussy] = [0f, 0.260f, 0.446f, 0.576f, 0.670f, 0.744f, 0.806f, 0.857f, 0.904f, 0.947f, 1f],
        [Hole.Ass] = [0f, 0.234f, 0.355f, 0.446f, 0.524f, 0.597f, 0.667f, 0.736f, 0.807f, 0.882f, 1f]
    };

    private static float Level(Hole hole, float share)
    {
        if (!AreaToLevel.TryGetValue(hole, out var table)) return share;
        var x = Mathf.Clamp(share, 0f, 1f) * (table.Length - 1);
        var i = Math.Min((int)x, table.Length - 2);
        return Mathf.Lerp(table[i], table[i + 1], x - i);
    }

    private static float GirthFor(Creature? enemy) => enemy?.CombatState?.Encounter?.RoomType switch
    {
        RoomType.Boss => 1.8f,
        RoomType.Elite => 1.35f,
        _ => 1.0f
    };

    private void Withdraw(Inset inset)
    {
        if (inset.Mode == Mode.Out) return;
        inset.Mode = Mode.Out;
        inset.Depth = -1f;
        inset.Anim.Play("out");
    }

    /// <summary>Any card played: the thrusting stops. The cock stays where it is.</summary>
    public void CardPlayed()
    {
        foreach (var inset in _insets.Values)
        {
            if (inset.Mode != Mode.Thrusting) continue;
            inset.Mode = Mode.Resting;
        }
    }

    /// <summary>An Attack removed HP: thrust and small spurt in its hole, and keep thrusting.</summary>
    public void Hit(Hole hole, Creature? enemy)
    {
        foreach (var (h, other) in _insets)
        {
            if (h != hole) Withdraw(other);
        }
        if (!_insets.TryGetValue(hole, out var inset)) return;   // Skin: nothing is in use

        inset.Material.SetShaderParameter("girth", GirthFor(enemy));

        var busy = inset.Anim.IsPlaying() && inset.Anim.CurrentAnimation != "out";
        if (!busy)
        {
            var entering = inset.Mode == Mode.Out;
            inset.Anim.Play(entering ? "attack_in" : "attack");
            inset.Hold = entering ? 0.97f : 0.62f;
        }
        inset.Mode = Mode.Thrusting;
        inset.Phase = 0f;        // both attack animations end at depth 0.1, where the idle thrust starts
        inset.Depth = 0.1f;
    }

    /// <summary>The enemy finished: big spurts in the hole, then out.</summary>
    public void Finish(Hole hole, Creature? enemy)
    {
        foreach (var (h, other) in _insets)
        {
            if (h != hole) Withdraw(other);
        }
        if (!_insets.TryGetValue(hole, out var inset)) return;

        inset.Material.SetShaderParameter("girth", GirthFor(enemy));
        var entering = inset.Mode == Mode.Out;
        inset.Anim.Play(entering ? "finish_in" : "finish");
        inset.Hold = entering ? 1.6f : 1.25f;
        inset.Mode = Mode.Out;   // both finish animations end with the cock out
        inset.Depth = -1f;
    }
}
